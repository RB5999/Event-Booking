// Helper to create dates relative to today for reliable testing of Today, Tomorrow, and This Weekend
const getRelativeDate = (offsetDays) => {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
};

// Find the next upcoming Friday/Saturday/Sunday
const getWeekendOffset = () => {
  const day = new Date().getDay(); // 0 is Sun, 5 is Fri, 6 is Sat
  if (day === 5) return 0; // Today is Friday
  if (day === 6) return 0; // Today is Saturday
  if (day === 0) return 0; // Today is Sunday
  return 5 - day; // Days until upcoming Friday
};

